  var LANG_META = { en: { dir: 'ltr', label: 'English', next: 'en' } };
  var current = 'en';
  // A browser that stored `ab_lang = fa` from the bilingual era must not keep
  // anything around: the key is dropped so nothing can read it back.
  try { localStorage.removeItem('ab_lang'); } catch (e) { /* storage off */ }

  function t(key) {
    var v = DICT.en[key];
    return v != null ? v : key;
  }
  function meta() { return LANG_META.en; }
  function getLang() { return current; }
  /** English only — kept so old call sites do not throw. */
  function setLang() { apply(); }
  function toggle() { apply(); }

  /** Apply translations to all [data-i18n] elements + html dir/lang. */
  function apply() {
    document.documentElement.lang = 'en';
    document.documentElement.dir = 'ltr';
    if (document.body) document.body.setAttribute('data-lang', 'en');
    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      nodes[i].textContent = t(nodes[i].getAttribute('data-i18n'));
    }
    var phNodes = document.querySelectorAll('[data-i18n-placeholder]');
    for (var j = 0; j < phNodes.length; j++) {
      phNodes[j].setAttribute('placeholder', t(phNodes[j].getAttribute('data-i18n-placeholder')));
    }
    document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang: current } }));
  }

  window.I18N = { t: t, apply: apply, setLang: setLang, toggle: toggle, getLang: getLang, meta: meta };
