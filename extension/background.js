/* ============================================================
   background.js — service worker (Step 13, extended in Step 31).
   - Performs the secure POST /run to the backend. Doing the fetch
     here (extension-privileged, with host_permissions) avoids the
     page-context CORS restrictions a content script would hit.
   - Step 31: makes the extension a thin client of the SAME backend the
     dashboard panel uses (Model A): it can list saved workflows
     (GET /workflows/:userId), run a saved workflow
     (POST /workflows/:userId/:workflowId/run), open the panel tab, and
     stream a job's live events over SSE — forwarding each event to the
     popup so it can paint per-node tick/error (mirroring Step 26).
   - Relays a few control messages from the popup to the active tab's
     content script (picker/recorder toggles).

   Settings (backend base URL, API key, userId) live in
   chrome.storage.local: ab_baseUrl, ab_apiKey, ab_userId.
   API key is never logged.

   Pure URL/parse/event logic is shared with the popup (and unit tests)
   via lib/ab-core.js — imported here as the global ABCore.
   ============================================================ */
'use strict';

// Service workers can pull in classic scripts synchronously. ab-core.js is a
// pure, DOM-free module that also runs in the popup and in vitest (one source
// of truth for URL building, list parsing and live-event mapping).
try { importScripts('lib/ab-core.js'); } catch (e) { /* ABCore optional fallback below */ }

// ab-handoff.js is the Local half of the Remote <-> Local switch. It lives HERE
// rather than in the popup on purpose: restoring a session opens N tabs and then
// reports completion, and the popup is destroyed the instant the user clicks
// away or Chrome moves focus to a new tab. A restore hosted in the popup would
// be killed mid-sequence, leaving some tabs open, nothing focused and the server
// still waiting -- exactly the "half-moved browser" state the ordering inside
// applyHandoff() is designed to avoid. The worker outlives the popup, so the
// popup only sends a message and the sequence completes regardless.
try { importScripts('lib/ab-handoff.js'); } catch (e) { /* ABHandoff optional; guarded at use */ }

// Optional, and present ONLY in the copy the server side-loads into the REMOTE
// browser (generated by src/core/InspectorExtension.ts). It is absent from the
// authored `extension/` directory and from any hand-installed copy, so the
// failure to import is the normal case for a user's own Chrome — hence a plain
// swallow rather than a warning.
try { importScripts('bootstrap.config.js'); } catch (e) { /* not a managed copy */ }

/**
 * Apply the server's bootstrap settings as DEFAULTS.
 *
 * WHY THIS EXISTS
 * ---------------
 * When the server side-loads this extension into the remote browser, the fresh
 * profile has an EMPTY `chrome.storage.local`. Without this, the popup would open
 * inside a remote desktop asking the user for the address and API token of the
 * very server that just launched the browser they are looking at — something
 * they cannot read from in there, and should not have to.
 *
 * WHY IT CAN ONLY EVER FILL IN BLANKS
 * -----------------------------------
 * Each key is written only when it is currently empty. A user who typed their own
 * base URL or key keeps it, on this launch and on every launch after — a managed
 * default that silently reverted a deliberate setting would be far worse than no
 * default at all. That is also why it is not `chrome.storage.local.set(all)`.
 */
async function applyBootstrapDefaults() {
  if (typeof AB_BOOTSTRAP === 'undefined' || !AB_BOOTSTRAP) return;
  var current = await new Promise(function (resolve) {
    chrome.storage.local.get(['ab_baseUrl', 'ab_apiKey', 'ab_userId'], function (s) {
      resolve(s || {});
    });
  });

  var patch = {};
  if (!current.ab_baseUrl && AB_BOOTSTRAP.baseUrl) patch.ab_baseUrl = AB_BOOTSTRAP.baseUrl;
  if (!current.ab_apiKey && AB_BOOTSTRAP.apiKey) patch.ab_apiKey = AB_BOOTSTRAP.apiKey;
  if (!current.ab_userId && AB_BOOTSTRAP.userId) patch.ab_userId = AB_BOOTSTRAP.userId;
  if (!Object.keys(patch).length) return;

  await new Promise(function (resolve) {
    chrome.storage.local.set(patch, function () { resolve(); });
  });
}

// On install AND on every worker start: an MV3 service worker is killed when
// idle, and `onInstalled` does not fire again when it is revived. Running it on
// load as well is what makes the settings reliably present.
if (chrome.runtime && chrome.runtime.onInstalled) {
  chrome.runtime.onInstalled.addListener(function () {
    applyBootstrapDefaults().catch(function () { /* defaults are best-effort */ });
  });
}
var abBootstrapReady = applyBootstrapDefaults().catch(function () { /* best-effort */ });

/**
 * WHICH BROWSER IS THIS EXTENSION RUNNING IN — 'local' or 'remote'?
 *
 * WHY THIS EXISTS
 * ---------------
 * Reported defect: the Remote approval Alert appeared in the operator's OWN
 * Chrome while they were working in LOCAL mode. The binding contract is now:
 *
 *   LOCAL  = the browser runtime on the SAME server as the application.
 *            Nothing to enter — no Base URL, no API Key, no Authorization Code —
 *            and NO Remote Approval Alert. The server resolves its own internal
 *            address and binds the target field itself.
 *   REMOTE = a browser on the server's infrastructure. Its address is resolved
 *            automatically from the server's public configuration, still with no
 *            API Key and no Authorization Code to type, and it is the ONLY
 *            environment that raises the Remote Approval Alert.
 *
 * The prompt is delivered by polling GET /inspector/consent, and that route can
 * only scope by account. Two browsers signed into the SAME account are
 * indistinguishable to it — which is precisely why the server-owned Chrome and
 * the user's Chrome both received the same question. The browser therefore has
 * to say which one it is, and this is that statement.
 *
 * WHY `AB_BOOTSTRAP.managed` IS THE RIGHT SIGNAL
 * ----------------------------------------------
 * `bootstrap.config.js` is GENERATED by src/core/InspectorExtension.ts and
 * copied in only when the server side-loads this extension into the browser it
 * launched itself. It is absent from the authored `extension/` directory and
 * from every hand-installed copy (see the guarded importScripts at the top of
 * this file). So its presence is not a preference and not a heuristic: it is the
 * server's own record of having created this browser. A user's Chrome cannot
 * acquire it by configuring anything, which is what makes the answer
 * unforgeable from the user side.
 *
 * ── WHICH ANSWER THAT PRESENCE MEANS, AND WHY IT FLIPPED ─────────────────────
 * A managed copy means THIS IS THE BROWSER ON THE SERVER, and under the correct
 * naming that browser is `local` — local to the project:
 *
 *   «وقتی لوکال می‌زنم باید مرورگر لوکال سرور بالا بیاید ولی برعکس است»
 *
 * A previous revision returned 'remote' here for exactly the same condition. It
 * was reading the names from the OPERATOR's point of view ("the server is far
 * away from me, so it is remote"), while the server reads them from the
 * project's. Two points of view, one field, opposite answers — which is how the
 * approval prompt ended up gated on the wrong browser.
 *
 * An unmanaged copy — a Chrome the operator installed this into themselves — is
 * `remote`: a machine this server does not own and cannot launch.
 *
 * WHY IT IS NOT THE BACKEND URL
 * -----------------------------
 * The obvious-looking test — "is ab_baseUrl loopback?" — is WRONG and is the
 * conflation this project keeps having to undo. A LOCAL browser is perfectly
 * entitled to drive a REMOTE backend over a public domain:
 *
 *   Backend Base URL   = WHERE THE SERVER IS
 *   Browser Environment = WHICH BROWSER DOES THE PICKING
 *
 * Those are independent, and deciding one from the other is how a local session
 * against a hosted backend ends up classified as remote and gets the Alert.
 *
 * WHY IT DEFAULTS TO 'remote'
 * ---------------------------
 * The failure modes are not symmetric, and the safe default moved with the
 * meaning. The prompt belongs to the server's own shared browser (`local`),
 * because that is the one window that outlives a targeting run and can be
 * holding the previous field's address. So:
 *
 *   Guessing 'local' in an operator's own Chrome would start the approval loop
 *   in a browser that must never run it — it would poll for, and could accept,
 *   prompts raised for a browser it is not. That is the unrecoverable direction.
 *
 *   Guessing 'remote' in the server's browser withholds a prompt. Recoverable:
 *   the operator sees no approval card and can act from the dashboard.
 *
 * So the default is the withholding one, as before — it is only the LABEL that
 * changed sides.
 */
function browserEnvironment() {
  return abBootstrapReady.then(function () {
    try {
      // Seeded by the server = the browser the server launched = LOCAL.
      if (typeof AB_BOOTSTRAP !== 'undefined' && AB_BOOTSTRAP && AB_BOOTSTRAP.managed === true) {
        return 'local';
      }
    } catch (e) { /* fall through to the safe answer */ }
    return 'remote';
  });
}

function getSettings() {
  // Await the bootstrap before reading, so the FIRST request out of a freshly
  // seeded extension is already configured instead of failing with
  // `no_base_url` and needing a retry the user has to guess at.
  return abBootstrapReady.then(function () {
    return new Promise(function (resolve) {
      chrome.storage.local.get(['ab_baseUrl', 'ab_apiKey', 'ab_userId'], function (s) {
        resolve({
          baseUrl: (s && s.ab_baseUrl) || '',
          apiKey: (s && s.ab_apiKey) || '',
          userId: (s && s.ab_userId) || 'local'
        });
      });
    });
  });
}

// Prefer the shared ABCore.normalizeBase; keep a tiny local fallback so the
// worker still functions if importScripts ever fails.
function normalizeBase(url) {
  if (typeof ABCore !== 'undefined' && ABCore.normalizeBase) return ABCore.normalizeBase(url);
  var u = String(url || '').trim();
  if (!u) return '';
  if (!/^https?:\/\//i.test(u)) u = 'http://' + u;
  return u.replace(/\/+$/, '');
}

// Small JSON fetch helper that always returns { ok, status, data, error? }.
async function apiFetch(url, opts, apiKey) {
  var headers = Object.assign(
    { 'Content-Type': 'application/json' },
    apiKey ? { 'x-api-key': apiKey } : {},
    (opts && opts.headers) || {}
  );
  try {
    var res = await fetch(url, Object.assign({}, opts, { headers: headers }));
    var text = await res.text();
    var data;
    try { data = text ? JSON.parse(text) : null; } catch (e) { data = { raw: text }; }
    if (!res.ok) return { ok: false, error: 'http_' + res.status, status: res.status, data: data };
    return { ok: true, status: res.status, data: data };
  } catch (e) {
    return { ok: false, error: 'network', message: String((e && e.message) || e) };
  }
}

/* ============================================================================
   ALL BACKEND CALLS BELOW RESOLVE THEIR CONTEXT INTERNALLY.
   ----------------------------------------------------------------------------
   Each of these used to open with the same two lines:

       if (!base)       return { ok: false, error: 'no_base_url' };
       if (!cfg.apiKey) return { ok: false, error: 'no_api_key' };

   Those refusals were the reason the popup had a Base URL box and an API Key
   box: something had to fill the values the worker was demanding. Both
   environments of this product already know their own backend — LOCAL is the
   browser runtime on the same server as the application, REMOTE is side-loaded
   by that server with its address baked into bootstrap.config.js — so the
   demand was asking the user to re-type a value the software already had.

   They now share inspectorContext(), which resolves the address from seeded
   storage, then the bootstrap, then the server-local loopback, and passes the
   API key through when known rather than insisting on it. See its header for
   the full reasoning. The only failure left is one no typing can fix.
   ============================================================================ */

/** Shared guard: resolve the internal context or report the one real failure. */
function contextFailure(ctx) {
  if (ctx && ctx.error) return { ok: false, error: ctx.error };
  return null;
}

// Send the recorded steps to the backend as an inline Flow (POST /run).
async function sendFlow(payload) {
  var ctx = await inspectorContext();
  var bad = contextFailure(ctx);
  if (bad) return bad;

  var steps = Array.isArray(payload && payload.steps) ? payload.steps : [];
  if (!steps.length) return { ok: false, error: 'no_steps' };

  var body = { userId: ctx.userId, steps: steps, headless: true };
  if (payload && payload.webhookUrl) body.webhookUrl = payload.webhookUrl;
  if (payload && typeof payload.headless === 'boolean') body.headless = payload.headless;

  var url = (typeof ABCore !== 'undefined' && ABCore.buildRunInlineUrl)
    ? ABCore.buildRunInlineUrl(ctx.base, { wait: !!(payload && payload.wait) })
    : ctx.base + '/run';
  return apiFetch(url, { method: 'POST', body: JSON.stringify(body) }, ctx.apiKey);
}

// Validate connectivity via GET /me. Returns data so the popup can resolve the
// canonical userId, and reports the resolved backend so the popup can DISPLAY
// the address instead of asking for it.
async function checkConnection() {
  var ctx = await inspectorContext();
  var bad = contextFailure(ctx);
  if (bad) return bad;
  var res = await apiFetch(ctx.base + '/me', { method: 'GET' }, ctx.apiKey);
  res.baseUrl = ctx.base;
  res.baseUrlSource = ctx.baseUrlSource;
  return res;
}

// Step 31: list the user's saved workflows — the SAME list the panel shows.
async function listWorkflows() {
  var ctx = await inspectorContext();
  var bad = contextFailure(ctx);
  if (bad) return bad;
  var res = await apiFetch(ctx.base + '/workflows/' + encodeURIComponent(ctx.userId), { method: 'GET' }, ctx.apiKey);
  if (res.ok && typeof ABCore !== 'undefined' && ABCore.parseWorkflowList) {
    res.workflows = ABCore.parseWorkflowList(res.data);
  }
  return res;
}

// Step 31: run a saved, versioned workflow (Model B contract, shared with the
// API client) and return the jobId so the popup can subscribe to live events.
async function runSavedWorkflow(payload) {
  var ctx = await inspectorContext();
  var bad = contextFailure(ctx);
  if (bad) return bad;
  var workflowId = payload && payload.workflowId;
  if (!workflowId) return { ok: false, error: 'no_workflow_id' };

  var userId = ctx.userId;
  var url = (typeof ABCore !== 'undefined' && ABCore.buildRunSavedUrl)
    ? ABCore.buildRunSavedUrl(ctx.base, userId, workflowId, { wait: !!(payload && payload.wait) })
    : ctx.base + '/workflows/' + encodeURIComponent(userId) + '/' + encodeURIComponent(workflowId) + '/run';

  var body = {};
  if (payload && payload.triggerData) body.triggerData = payload.triggerData;
  if (payload && typeof payload.headless === 'boolean') body.headless = payload.headless;

  var res = await apiFetch(url, { method: 'POST', body: JSON.stringify(body) }, ctx.apiKey);
  if (res.ok && typeof ABCore !== 'undefined' && ABCore.extractJobId) {
    res.jobId = ABCore.extractJobId(res.data);
  }
  return res;
}

// ---- Live (SSE) streaming -------------------------------------------------
// We stream a job's events here in the worker (host-privileged) and forward
// each mapped status delta to the popup via runtime messages, so the popup can
// paint tick/error per node even though EventSource cannot set headers.
var liveControllers = {}; // jobId -> AbortController

function broadcast(message) {
  try { chrome.runtime.sendMessage(message, function () { void chrome.runtime.lastError; }); } catch (e) { /* popup closed */ }
}

async function startLive(payload) {
  var ctx = await inspectorContext();
  var bad = contextFailure(ctx);
  if (bad) return bad;
  var cfg = { baseUrl: ctx.base, apiKey: ctx.apiKey, userId: ctx.userId };
  var base = ctx.base;
  var jobId = payload && payload.jobId;
  if (!jobId) return { ok: false, error: 'no_job_id' };
  var userId = (payload && payload.userId) || ctx.userId;

  // stop a previous stream for the same job if any
  if (liveControllers[jobId]) { try { liveControllers[jobId].abort(); } catch (e) { /* noop */ } }
  var controller = new AbortController();
  liveControllers[jobId] = controller;

  var url = (typeof ABCore !== 'undefined' && ABCore.buildSseUrl)
    ? ABCore.buildSseUrl(base, userId, jobId, cfg.apiKey)
    : base + '/live/sse/' + encodeURIComponent(userId) + '/' + encodeURIComponent(jobId) + '?api_key=' + encodeURIComponent(cfg.apiKey);

  // Drive the SSE stream with fetch + ReadableStream (works in MV3 workers,
  // unlike EventSource which is unavailable there).
  (async function pump() {
    try {
      var res = await fetch(url, { method: 'GET', signal: controller.signal });
      if (!res.ok || !res.body) {
        broadcast({ type: 'AB_LIVE_ERROR', jobId: jobId, error: 'http_' + res.status });
        cleanupLive(jobId);
        return;
      }
      var reader = res.body.getReader();
      var decoder = new TextDecoder();
      var buf = '';
      while (true) {
        var chunk = await reader.read();
        if (chunk.done) break;
        buf += decoder.decode(chunk.value, { stream: true });
        var idx;
        // SSE frames are separated by a blank line.
        while ((idx = buf.indexOf('\n\n')) !== -1) {
          var frame = buf.slice(0, idx);
          buf = buf.slice(idx + 2);
          handleSseFrame(jobId, frame);
        }
      }
      broadcast({ type: 'AB_LIVE_END', jobId: jobId });
    } catch (e) {
      if (!controller.signal.aborted) {
        broadcast({ type: 'AB_LIVE_ERROR', jobId: jobId, error: 'network', message: String((e && e.message) || e) });
      }
    } finally {
      cleanupLive(jobId);
    }
  })();

  return { ok: true, jobId: jobId };
}

function handleSseFrame(jobId, frame) {
  // Parse the "event:" and "data:" lines of one SSE frame.
  var lines = frame.split('\n');
  var dataLines = [];
  for (var i = 0; i < lines.length; i++) {
    var line = lines[i];
    if (line.indexOf('data:') === 0) dataLines.push(line.slice(5).trimStart());
  }
  if (!dataLines.length) return;
  var raw = dataLines.join('\n');
  var ev;
  try { ev = JSON.parse(raw); } catch (e) { return; }

  var status = (typeof ABCore !== 'undefined' && ABCore.mapLiveEventToStatus)
    ? ABCore.mapLiveEventToStatus(ev) : null;
  broadcast({ type: 'AB_LIVE_EVENT', jobId: jobId, event: ev, status: status });

  if (typeof ABCore !== 'undefined' && ABCore.isTerminalEvent && ABCore.isTerminalEvent(ev)) {
    var ctrl = liveControllers[jobId];
    if (ctrl) { try { ctrl.abort(); } catch (e) { /* noop */ } }
  }
}

function cleanupLive(jobId) {
  if (liveControllers[jobId]) { delete liveControllers[jobId]; }
}

function stopLive(payload) {
  var jobId = payload && payload.jobId;
  if (jobId && liveControllers[jobId]) {
    try { liveControllers[jobId].abort(); } catch (e) { /* noop */ }
    cleanupLive(jobId);
  }
  return { ok: true };
}

// Step 31: open (or focus) the dashboard panel — the SAME UI the extension is
// a thin client of.
async function openPanel() {
  var ctx = await inspectorContext();
  var bad = contextFailure(ctx);
  if (bad) return bad;
  var base = ctx.base;
  var url = (typeof ABCore !== 'undefined' && ABCore.buildPanelUrl) ? ABCore.buildPanelUrl(base) : base + '/';
  return new Promise(function (resolve) {
    chrome.tabs.create({ url: url }, function (tab) {
      if (chrome.runtime.lastError) { resolve({ ok: false, error: 'open_failed' }); return; }
      resolve({ ok: true, tabId: tab && tab.id });
    });
  });
}

/* ============================================================
   ELEMENT INSPECTOR

   The content script cannot POST the pick itself: a fetch from page context is
   subject to the page's CSP and to CORS against the backend origin. The worker
   holds host_permissions, so the request belongs here — same reason sendFlow
   lives here.

   THE DESTINATION IS A TARGET FIELD, AND IT IS BOUND ONCE
   ------------------------------------------------------
   This worker used to mint its own `ext-…` session id and submit picks under it.
   The dashboard claimed nodes under a per-TAB `ui-…` id, and the server compared
   the two for equality — two independently generated strings, so every pick was
   refused. The id was then read back from the server purely to satisfy the
   comparison, a round trip that carried no information: the value sent was the
   value the server had handed over moments earlier.

   That whole mechanism is gone. The destination is now a Target Field the
   project registers, addressed by `targetFieldId`, and this extension is bound
   to it ONCE — by the SERVER, not by the user:

     LOCAL  the server binds the field internally when the crosshair is used.
            Nothing is typed and nothing is shown to approve.
     REMOTE the server raises an approval request; answering it delivers the
            target (see consentDecide). Still nothing is typed.

   After the binding, ordinary sends carry only the id and whatever key the
   bootstrap supplied — no session, no echo, nothing to keep in sync.

   The extension therefore stores exactly one new thing: which Target Field it is
   currently sending to. It is persisted rather than re-derived so it survives
   worker restarts (MV3 kills workers aggressively).
   ============================================================ */

/**
 * Resolve the backend context for the inspector calls — WITHOUT asking the user.
 *
 * WHAT THIS USED TO DO, AND WHY IT WAS THE DEFECT
 * ----------------------------------------------
 * It read `ab_baseUrl` and `ab_apiKey` out of storage and, if either was blank,
 * refused with `no_base_url` / `no_api_key`. Those two strings were the engine
 * of the whole reported problem: the popup rendered them as "set the Base URL
 * first" / "set the API Key first", which is why it HAD a Base URL box and an
 * API key box at all. Every credential control in the extension existed to
 * satisfy this function.
 *
 * That is backwards for both environments of this product:
 *
 *   LOCAL BROWSER  = the browser runtime on the SAME server the application runs
 *                    on. The backend is not merely reachable from here, it is the
 *                    process that launched this browser. Its address is internal
 *                    and known; there is nothing for a human to look up.
 *   REMOTE BROWSER = the browser on the server's own infrastructure, side-loaded
 *                    with this extension by that same server, which wrote its own
 *                    public address and token into bootstrap.config.js on the way
 *                    in (src/core/InspectorExtension.ts).
 *
 * In both cases the server is the authority on its own address and token, and it
 * has already stated both. Asking the user to retype them was asking them to
 * re-supply — by hand, from inside a browser they may not be able to read them
 * from — values that were present and correct all along.
 *
 * WHAT IT DOES NOW
 * ----------------
 * Three internal sources, in order of authority, and no user input anywhere:
 *
 *   1. Storage, which `applyBootstrapDefaults()` has already seeded from the
 *      server's own bootstrap. This is the normal case and it is exact.
 *   2. `AB_BOOTSTRAP` directly, in case storage was cleared after seeding — the
 *      generated file is still importable, so the answer is still available.
 *   3. The server-local loopback default. Reached only when there is no bootstrap
 *      at all, which is a hand-installed copy driving a server on this machine.
 *      This is a guess, but it is the RIGHT guess for exactly the case that has
 *      no other source, and it is the same address the server publishes to its
 *      own managed copies (InspectorExtension.serverBaseUrl()).
 *
 * The API key is passed through when known and OMITTED when not — never demanded.
 * `apiFetch()` already sends no `x-api-key` header for an empty value, and a
 * server-local request without one is a request the backend is entitled to
 * accept or refuse on its own terms. Refusing it HERE, before it is made, is the
 * behaviour that produced a credential form.
 *
 * The single remaining failure is `runtime_context_unavailable`, and it means
 * something the user genuinely cannot fix by typing: no address could be
 * resolved from any internal source. The popup says so in those terms.
 */
/**
 * The port to assume when NOTHING has told us better.
 *
 * A last resort, and it is a genuine guess — which is why the seeded bootstrap
 * carries the real one (`AB_BOOTSTRAP.port`) and is preferred over this. It used
 * to be baked into a hardcoded `http://127.0.0.1:3000` constant, so a server
 * started with `PORT=8080` seeded a browser that talked to nothing and reported
 * a network error the operator could do nothing about:
 *
 *   «روی 127.0.0.1:پورت پروژه که بالا آمده رو خودش ست کنه»
 */
var LOOPBACK_PORT_FALLBACK = 3000;

/** Build the server-local address for a port. LOCAL environment only. */
function loopbackBase(port) {
  var n = parseInt(port, 10);
  if (!isFinite(n) || n <= 0 || n > 65535) n = LOOPBACK_PORT_FALLBACK;
  return 'http://127.0.0.1:' + n;
}

async function inspectorContext() {
  var cfg = await getSettings();

  // 1 — what the server seeded (or what a previous version stored).
  var base = normalizeBase(cfg.baseUrl);
  var apiKey = cfg.apiKey || '';
  var userId = cfg.userId || 'local';
  var source = base ? 'bootstrap' : '';

  // 2 — the generated bootstrap itself, if storage lost it.
  if (!base || !apiKey) {
    try {
      if (typeof AB_BOOTSTRAP !== 'undefined' && AB_BOOTSTRAP) {
        if (!base && AB_BOOTSTRAP.baseUrl) {
          base = normalizeBase(AB_BOOTSTRAP.baseUrl);
          source = 'bootstrap';
        }
        if (!apiKey && AB_BOOTSTRAP.apiKey) apiKey = AB_BOOTSTRAP.apiKey;
        if ((!userId || userId === 'local') && AB_BOOTSTRAP.userId) userId = AB_BOOTSTRAP.userId;
      }
    } catch (e) { /* not a managed copy — fall through to the loopback default */ }
  }

  // 3 — the server-local default. The LOCAL contract is "the browser runtime on
  //     the same server", so loopback is not a fallback in spirit: it IS the
  //     address of a server-local backend, and it is what the server itself
  //     publishes to the copies it seeds.
  //
  //     The PORT comes from the seeded bootstrap when there is one, so this
  //     tracks the port the server actually listens on instead of assuming the
  //     default. Only a copy that was never seeded falls back to the guess.
  if (!base) {
    var seededPort = 0;
    try {
      if (typeof AB_BOOTSTRAP !== 'undefined' && AB_BOOTSTRAP && AB_BOOTSTRAP.port) {
        seededPort = AB_BOOTSTRAP.port;
      }
    } catch (e) { /* unmanaged copy — the guess below is all there is */ }
    base = normalizeBase(loopbackBase(seededPort));
    source = 'server-local';
  }

  if (!base) return { error: 'runtime_context_unavailable' };

  // `apiKey` may legitimately be '' here. That is not an error state: it is a
  // request the backend gets to judge, and the alternative — refusing to ask —
  // is what put an API key box on screen.
  return { base: base, apiKey: apiKey, userId: userId, baseUrlSource: source };
}

