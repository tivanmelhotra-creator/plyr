/**
 * Which BROWSER ENVIRONMENT the field this extension is paired with was
 * targeted in — 'local' or 'remote'.
 *
 * Recorded so the popup can state it rather than leave the operator guessing,
 * and read from the SERVER's target record, never asserted by the extension.
 * It is a third, separate concept from both of the ids above and from the
 * automation Browser Mode:
 *
 *   Browser Environment = LOCAL / REMOTE   (which browser the pick happens in)
 *   Session / Handoff   = as_… remote infra (not involved here at all)
 *   targetFieldId       = the destination   (where the value lands)
 *
 * The popup's CONNECTION tab shows a local/remote pair too, but that is derived
 * from whether the BACKEND URL is loopback — where the server is, not which
 * browser is doing the targeting. Conflating them is the confusion this field
 * exists to end.
 */
function getTargetEnvironment() {
  return new Promise(function (resolve) {
    chrome.storage.local.get(['ab_targetEnvironment'], function (s) {
      resolve((s && s.ab_targetEnvironment) || '');
    });
  });
}

function setTargetEnvironment(env) {
  var v = (env === 'local' || env === 'remote') ? env : '';
  return new Promise(function (resolve) {
    chrome.storage.local.set({ ab_targetEnvironment: v }, function () { resolve(v); });
  });
}

/**
 * What is this extension attached to — which mode, which fields are open, and
 * which of them may it write to?
 *
 * Asked when the popup opens, so the user sees the answer before picking rather
 * than discovering it from a failed send. `authorized` comes back scoped to THIS
 * API key, so the popup can show "connected to this Field" truthfully instead of
 * listing fields the extension cannot actually reach.
 */
async function inspectorSession() {
  var ctx = await inspectorContext();
  if (ctx.error) return { ok: false, error: ctx.error };
  var res = await apiFetch(ctx.base + '/inspector/session', { method: 'GET' }, ctx.apiKey);
  var data = (res && res.data) || {};
  var chosen = await getTargetFieldId();

  // The address this request actually used, reported back so the popup can SHOW
  // the resolved backend instead of echoing an input box. Sent on failure too —
  // "cannot reach X" is only actionable if X is named. `baseUrlSource` says
  // whether it came from the server's bootstrap or the server-local default,
  // which is the difference between a managed browser and a hand-installed one.
  res.baseUrl = ctx.base;
  res.baseUrlSource = ctx.baseUrlSource;

  var authorized = data.authorized || [];
  var isAuthorized = authorized.some(function (b) { return b.targetFieldId === chosen; });

  res.targetFieldId = chosen;
  res.authorized = isAuthorized;
  // The full record for the DESTINATION panel: node name, field name, label.
  var target = (data.targets || []).filter(function (t) {
    return t.targetFieldId === chosen;
  })[0] || null;
  res.target = target;

  // ── The durable half of the answer ───────────────────────────────────────
  //
  // The stored pairing key is preferred over the live target's, because the
  // point of a pairing is that it outlives the address: when the dashboard has
  // not re-registered the field yet, `target` is null and the address is stale,
  // yet the operator must still be told they are paired and will NOT be asked
  // for another code.
  var storedKey = await getPairingKey();
  var pairingKey = storedKey || (target && target.pairingKey) || '';
  var pairings = data.pairings || [];
  res.pairingKey = pairingKey;
  res.paired = !!pairingKey && pairings.some(function (p) {
    return p && p.pairingKey === pairingKey;
  });

  // Environment is taken from the SERVER's target record — the extension does
  // not get to assert which browser it is. The stored value is only a fallback
  // for when the field is not currently registered.
  var env = (target && target.environment) || (await getTargetEnvironment());
  res.environment = (env === 'local' || env === 'remote') ? env : '';
  if (target && target.environment) await setTargetEnvironment(target.environment);

  // A pairing the server no longer holds must not keep being displayed: the
  // operator would be told no code is needed and then be refused on send.
  if (pairingKey && !res.paired && pairings.length) await setPairingKey('');
  return res;
}

/**
 * inspectorPair() IS DELETED.
 *
 * It was the extension's half of the Authorization Code architecture: it POSTed
 * a user-typed code to `/inspector/pair`, and the server answered with the field
 * that code had been scoped to, which the extension then stored.
 *
 * That architecture is withdrawn. Neither environment issues a code any more:
 *
 *   LOCAL BROWSER  — the browser runtime on the same server as the application.
 *                    The server binds the target itself when the crosshair is
 *                    used; there is no credential and no prompt.
 *   REMOTE BROWSER — the server's own browser. It binds on the user APPROVING
 *                    the Remote Approval prompt, which is handled by
 *                    consentDecide() below.
 *
 * So there is nothing left for this function to redeem. Deleting it, rather than
 * leaving it unreachable, is deliberate: a live code-redemption path in the
 * worker is a working half of the removed flow, and the next UI that wanted to
 * "just add a code box" would find it already built and waiting.
 *
 * consentDecide() is its replacement, and the two are worth comparing — same
 * outcome (a stored target the extension did not choose), reached by ANSWERING a
 * question the server asked instead of by transcribing a secret the server
 * printed.
 */

/**
 * Forget the binding locally.
 *
 * Clears the durable key as well as the address — otherwise the popup would go
 * on reporting "bound" for a field this extension has deliberately let go of.
 * The server keeps its own record until the dashboard's explicit
 * `/inspector/targeting/unpair`; this is the extension's local half.
 */
async function inspectorUnpair() {
  await setTargetFieldId('');
  await setPairingKey('');
  await setTargetEnvironment('');
  return { ok: true };
}

/* ============================================================
   REMOTE TARGETING CONSENT
   ============================================================

   WHY THIS EXISTS

   The browser running on the server is, from this extension's point of view, an
   ordinary LOCAL browser. It loads this same code, and it addresses a submit
   with `ab_targetFieldId` out of chrome.storage.local.

   Historically the ONLY writer of that value was inspectorPair(), which redeemed
   an Authorization Code — a mechanism since removed entirely. REMOTE never issued
   a code even then, by explicit requirement, so on the remote path the value
   stayed empty, submitElement() refused locally with TARGET_NOT_AUTHORIZED before
   any HTTP request was made, and the operator saw:

     «ظاهرا نمیدونه به کدوم فیلد باید ارسال بشه» — Connection failed: network

   The server had granted a binding. Nothing had ever told the CLIENT which field
   it was for.

   WHY A PROMPT AND NOT AN AUTO-FILL

   The obvious shortcut is to have the extension ask "what is my current target?"
   and adopt the answer. That was rejected: with two nodes open there IS no
   single current target, and picking the most recent silently means a pick lands
   in the node the operator is no longer looking at, WITH a success message. That
   is strictly worse than the refusal it replaces, because a refusal is visible.
   It also breaks the standing rule «The Extension must NEVER be able to choose
   an arbitrary Target Field» — an extension that adopts whatever a list contains
   has chosen.

   So the server ASKS, naming the node and the field, and the human answers. A
   consent and a code are the same security object — one-time, server-issued,
   expiring, single-target, completable only by a person. The consent is merely
   addressed to a browser the server can already reach, so it can be DELIVERED
   instead of TRANSCRIBED. Approval is what attaches the destination, which is
   why the reply to a decision is stored exactly the way a redeemed code is.
   ============================================================ */

/**
 * What is this browser being asked to confirm?
 *
 * Returns the human-readable questions ONLY. The server withholds the target
 * address from this list on purpose (see ConsentPrompt in
 * src/core/RemoteTargetConsent.ts): if the address were here, this function
 * could store it and skip the prompt, which is the one thing the handshake
 * exists to prevent.
 */
async function consentList() {
  var ctx = await inspectorContext();
  if (ctx.error) return { ok: false, error: ctx.error, requests: [] };

  var env = await browserEnvironment();

  // A REMOTE browser — one on the operator's own machine — is answered here and
  // never asks the server.
  //
  // THE DIRECTION OF THIS GATE FLIPPED WITH THE NAMES. The approval prompt
  // belongs to the SERVER's own browser (`local`), because that is the single
  // shared window which outlives a targeting run and may still be holding the
  // previous field's address. A browser on the operator's desktop acquires its
  // target by redeeming an Authorization Code, which named exactly one field, so
  // there is nothing left for it to be asked.
  //
  // This is the FIRST of two independent gates, and the reason there are two is
  // that they fail differently. The server-side filter (pendingFor) protects a
  // browser running a CURRENT extension against a server that has a prompt
  // outstanding for the other environment. This one protects against the server
  // too: an older backend, a backend that has not been redeployed, or any future
  // route that forgets the filter, still cannot produce an Alert in the
  // operator's own browser, because there the request is not made at all.
  //
  // Returning `ok: true` with an empty list rather than an error is deliberate:
  // "nothing is pending for you" is the TRUTH here, because a REMOTE browser's
  // binding was completed by the redemption — a path that is complete on its own
  // and needs no prompt, no polling and no timeout. An error would make callers
  // back off and retry as if something were broken.
  if (env !== 'local') {
    return { ok: true, count: 0, requests: [], environment: env, skipped: 'remote' };
  }

  // Declared BOTH ways on purpose. The query string is what the route reads
  // first and is visible in a server log when diagnosing exactly this class of
  // bug; the header survives a proxy that rewrites or strips query strings.
  // src/Routes/mode.routes.ts accepts either and treats them identically.
  var res = await apiFetch(
    ctx.base + '/inspector/consent?environment=' + encodeURIComponent(env),
    { method: 'GET', headers: { 'x-browser-environment': env } },
    ctx.apiKey
  );
  var data = (res && res.data) || {};
  if (!res.ok) {
    return {
      ok: false,
      reason: data.reason || res.error,
      error: data.error || res.message || 'Could not ask the server what is pending.',
      requests: [],
      environment: env,
    };
  }
  return {
    ok: true,
    count: data.count || 0,
    requests: data.requests || [],
    environment: env,
  };
}

/**
 * The human pressed Allow (or Deny).
 *
 * Sends a `consentId` and a boolean — never a target. The destination comes back
 * FROM the server, decided before the prompt was ever raised, and storing it is
 * the line that makes the reported failure go away: it is the write to
 * `ab_targetFieldId` that REMOTE never had.
 *
 * Stores the durable pairing key and the environment alongside the target, so a
 * consent-granted binding survives an NDV reopen. If it did not, the operator
 * would be re-prompted every time and "click Allow every time" would simply be
 * a new spelling of the defect this work removes.
 *
 * ── WHICH BROWSER THIS BELONGS TO, AND THE CONTRADICTION IT RESOLVES ────────
 *
 * It applies to LOCAL alone — the browser runtime on the SAME server as the
 * project. That window is one shared, long-lived browser: it outlives a single
 * targeting run and may still be holding the previous field's address, so a
 * human has to say which of them the next pick belongs to. The Alert names the
 * node and the field, and pressing Allow is what writes `ab_targetFieldId`.
 *
 * REMOTE needs no counterpart. A browser on the operator's own machine acquires
 * its destination by redeeming an Authorization Code, and that code named
 * exactly one Target Field — so there is nothing left to be asked.
 *
 * THIS GATE POINTED THE OTHER WAY, AND THAT WAS A LIVE DEFECT, not merely a
 * stale comment. consentList() above admits `local` and turns `remote` away;
 * this one admitted `remote` and turned `local` away. The two together meant a
 * LOCAL browser could SEE the Alert and then be refused the moment it pressed
 * Allow — `wrong_environment` on the one environment that actually raises the
 * prompt, and no binding written at all. The old name `needsRemoteApproval` is
 * what let the pair read as consistent while they disagreed.
 */
async function consentDecide(payload) {
  var ctx = await inspectorContext();
  if (ctx.error) return { ok: false, error: ctx.error };

  var consentId = String((payload && payload.consentId) || '').trim();
  if (!consentId) {
    return { ok: false, reason: 'consent_not_found', error: 'Nothing to answer.' };
  }

  // A REMOTE browser cannot complete this grant, even if a consentId reaches it
  // somehow (a stale card left in a tab from an earlier LOCAL session, or a page
  // that guesses an id). Gating the LIST alone would leave the write to
  // `ab_targetFieldId` reachable, and that write is the whole point of the
  // handshake. A browser on the operator's own machine has no business answering
  // it because it never needed to: its field arrived with the Authorization Code
  // it redeemed, which is why the Alert is a LOCAL-only surface.
  //
  // MIRRORS consentList() EXACTLY — admit `local`, refuse everything else — and
  // that symmetry is the fix. While this said `remote`, the two gates disagreed
  // and the server's own browser was shown a prompt it was then forbidden to
  // answer.
  var env = await browserEnvironment();
  if (env !== 'local') {
    return {
      ok: false,
      reason: 'wrong_environment',
      // Names the path that DOES apply here, because a refusal the operator
      // cannot act on is only half an answer.
      error: 'This approval belongs to the browser running on the server. '
        + 'To connect a browser on your own machine, use the Authorization Code '
        + 'from the dashboard (Target This Field → Remote Browser).',
      environment: env,
    };
  }
  // Explicitly boolean: `approve: undefined` must never read as approval.
  var approve = (payload && payload.approve) === true;

  var res = await apiFetch(
    ctx.base + '/inspector/consent/decide',
    { method: 'POST', body: JSON.stringify({ consentId: consentId, approve: approve }) },
    ctx.apiKey
  );

  var data = res.data || {};
  if (!res.ok) {
    return {
      ok: false,
      reason: data.reason || res.error,
      error: data.error || res.message || 'That request could not be answered.',
    };
  }

  // Denied: the server attached nothing, so neither do we. Anything already
  // paired is left alone — declining a NEW field must not disconnect the field
  // this browser is currently working on.
  if (!data.approved) {
    return { ok: true, approved: false, consentId: consentId };
  }

  var target = data.target || null;
  var id = (data.binding && data.binding.targetFieldId) || data.targetFieldId
    || (target && target.targetFieldId) || '';
  await setTargetFieldId(id);

  var pairingKey = (data.binding && data.binding.pairingKey) || data.pairingKey
    || (target && target.pairingKey) || '';
  await setPairingKey(pairingKey);

  // Reuses the `env` declared above (a second `var env` here was a duplicate
  // declaration that silently shadowed nothing and only confused readers).
  //
  // The fallback is `local`, not `remote`: reaching this line at all means the
  // gate above admitted this browser, and it admits `local` only. A `remote`
  // default would have stamped the one environment that can never get here.
  env = (target && target.environment) || 'local';
  await setTargetEnvironment(env);

  return {
    ok: true,
    approved: true,
    consentId: consentId,
    targetFieldId: id,
    pairingKey: pairingKey,
    environment: env,
    target: target,
  };
}

/**
 * Deliver ONE confirmed attribute to the paired Target Field.
 *
 * §21: «the system sends exactly ONE Radio-selected value», so the payload
 * carries `sendAttribute` (the radio) and `displayAttributes` (the checkboxes,
 * which affect display only). The server recomputes the value from the element
 * it receives, so the `value` here is advisory.
 *
 * Refusals pass the backend's §27 code and sentence through UNCHANGED, because
 * "this Inspector is not authorized for that Field" is a fixable problem and a
 * generic failure message hides the fix.
 */
async function submitElement(payload) {
  var ctx = await inspectorContext();
  if (ctx.error) return { ok: false, error: ctx.error };

  var element = payload && payload.element;
  if (!element) return { ok: false, error: 'no_element' };

  // §22.5 — a radio must be selected. Refused here rather than sent, because the
  // only possible answer is a 409 and the message is the same either way.
  var send = (payload && payload.sendAttribute) || null;
  var attrName = send && String(send.name || '').trim();
  if (!attrName) {
    return {
      ok: false,
      reason: 'ATTRIBUTE_SEND_FAILED',
      error: 'Select one attribute to send.'
    };
  }

  // The destination must have been bound. Refusing locally saves a round trip
  // and names the actual fix — which is now an action in the PROJECT, not a
  // credential to type here. Was: 'Enter an Authorization Code first.'
  var targetFieldId = await getTargetFieldId();
  if (!targetFieldId) {
    return {
      ok: false,
      reason: 'TARGET_NOT_AUTHORIZED',
      error: 'This Inspector is not bound to a Field yet. In the project, click the '
        + 'crosshair on the field you want to fill (and approve the request if this '
        + 'is the remote browser).'
    };
  }

  var res = await apiFetch(
    ctx.base + '/inspector/element',
    {
      method: 'POST',
      body: JSON.stringify({
        targetFieldId: targetFieldId,
        element: element,
        displayAttributes: (payload && payload.displayAttributes) || [],
        sendAttribute: { name: attrName, value: send.value }
      })
    },
    ctx.apiKey
  );

  var data = res.data || {};
  if (!res.ok) {
    return {
      ok: false,
      reason: data.reason || res.error,
      error: data.error || res.message || 'The element could not be delivered.',
      targets: data.targets || []
    };
  }

  // §24: the confirmation NAMES the field, the attribute and the value — that is
  // what proves the value did not silently go somewhere else.
  return {
    ok: true,
    node: data.nodeName || '',
    field: data.fieldName || '',
    targetFieldId: data.targetFieldId || targetFieldId,
    attribute: data.attribute || attrName,
    value: data.value || '',
    delivery: data.delivery || null
  };
}

/* ============================================================================
   BROWSER ENVIRONMENT — THE LOCAL / REMOTE CHOICE, FROM INSIDE THE EXTENSION
   ----------------------------------------------------------------------------
   REPORTED, and the regression these two functions repair:

     «UI فعلی دیگر هیچ انتخابی برای LOCAL BROWSER / REMOTE BROWSER ندارد. طبق
      قرارداد نهایی، این انتخاب باید حتماً در Targeting flow باقی بماند. این را
      با Backend Connection اشتباه نکن.»

   The choice itself was never deleted from the product: the dashboard's own
   dialog (public/js/targeting-flow.js renderChooser) still offers both cards.
   What was missing is that the choice existed ONLY there. An operator working
   from the extension popup — which is where "Target this field" is reached in
   the browser being targeted — had no way to make it, so the environment was
   whatever the last dashboard interaction happened to record.

   WHAT THESE ARE NOT
   ------------------
   Not the Backend Connection. That is WHERE THE SERVER IS, it is resolved by
   the server, it is not a choice, and the controls that used to ask for it
   (#baseUrl, #apiKey, the Local/Remote BACKEND radio pair) are deleted and stay
   deleted. These two functions carry the third, separate concept:

     Browser Environment  LOCAL / REMOTE   <- WHICH BROWSER does the picking
     Backend location     resolved by the server, never asked
     targetFieldId        the destination, minted server-side

   NO NEW BACKEND. Both call the routes the dashboard chooser already calls,
   unchanged: GET /inspector/targeting/options and POST /inspector/targeting/
   begin. There is deliberately no new endpoint, no new grant path and no new
   binding rule — the server keeps deciding all of that, exactly as it does for
   the dashboard, which is what stops the two surfaces from disagreeing.
   ========================================================================== */

/**
 * Which environments may be chosen for this field right now, and what each one
 * would ask of the operator.
 *
 * A READ: it registers nothing, mints no destination and creates no pairing,
 * because merely opening a chooser the user may cancel must not leave state
 * behind. `available` / `needsInPageApproval` / `needsAuthorization` all come
 * from the server's own environmentOptions(), so the popup can never offer a
 * card the server would then refuse, nor promise "automatic" for a card that
 * is about to ask for something.
 *
 * The middle name USED TO BE `needsRemoteApproval`, and it was true for
 * `remote`. Both halves of that were wrong: the in-page approval is raised by
 * the server inside ITS OWN browser, so it belongs to LOCAL, and the word
 * "remote" in the identifier is exactly what made the mistake read as correct
 * for as long as it did.
 */
async function targetingOptions(payload) {
  var ctx = await inspectorContext();
  if (ctx.error) return { ok: false, error: ctx.error, options: [] };

  var nodeId = String((payload && payload.nodeId) || '').trim();
  var fieldKey = String((payload && payload.fieldKey) || '').trim();
  if (!nodeId || !fieldKey) return { ok: false, error: 'no_target_field', options: [] };

  var qs = '?nodeId=' + encodeURIComponent(nodeId) + '&fieldKey=' + encodeURIComponent(fieldKey);
  if (payload && payload.workflowId) qs += '&workflowId=' + encodeURIComponent(payload.workflowId);

  var res = await apiFetch(ctx.base + '/inspector/targeting/options' + qs, { method: 'GET' }, ctx.apiKey);
  var data = (res && res.data) || {};
  if (!res.ok) {
    return {
      ok: false,
      reason: data.reason || res.error,
      error: data.error || res.message || 'Could not ask the server which browsers are available.',
      options: []
    };
  }
  return {
    ok: true,
    options: data.options || [],
    paired: !!data.paired,
    localEnabled: !!data.localEnabled,
    pairingKey: data.pairingKey || ''
  };
}

/**
 * The operator chose an environment. Hand it to the server and store what comes
 * back.
 *
 * The ENVIRONMENT is the only thing sent. The binding, the address and the
 * credential all come back FROM the server, which is what keeps this surface
 * incapable of asserting a target for itself:
 *
 *   LOCAL   -> `openServerBrowser: true` plus a consent prompt. LOCAL means
 *              local TO THIS PROJECT: the browser on the same machine as the
 *              backend, which is therefore the one thing this server can
 *              actually launch. No Base URL, no API key and no Authorization
 *              Code are asked for, because there is no second machine to carry
 *              them to. What IS asked for is an approval inside that browser,
 *              and not out of distrust: ONE server browser is shared by every
 *              field and outlives any single pick, so it has to be told which
 *              field this one is. True whether or not it was already running:
 *
 *                «اگر بالا باشه که الرت میده، اگر بالا نباشه یکی بالا میاره و بعدش الرت میده»
 *
 *   REMOTE  -> `step: 'authorize'` and an `authorization` payload. REMOTE means
 *              remote FROM THIS PROJECT: the browser on the operator's own
 *              personal machine. Two machines, a real trust gap, so a Base URL
 *              and a fresh per-field code are required — and nothing is
 *              launched, because that browser is already open and this server
 *              cannot reach it.
 *
 * NEITHER branch stores the target here. LOCAL's destination is written by
 * consentDecide() when the human presses Allow; REMOTE's by inspectorPair()
 * when the code is redeemed. Storing it at BEGIN time would bind a field to a
 * browser that never answered — which is the whole reason both settling acts
 * exist. These two descriptions were previously attached to the wrong
 * environments, and that swap was the reported defect:
 *
 *     «وقتی لوکال میزنم باید مرورگر لوکال سرور بالا بیاد ولی برعکسه»
 */
async function targetingBegin(payload) {
  var ctx = await inspectorContext();
  if (ctx.error) return { ok: false, error: ctx.error };

  var environment = (payload && payload.environment) === 'local' ? 'local' : 'remote';
  var nodeId = String((payload && payload.nodeId) || '').trim();
  var fieldKey = String((payload && payload.fieldKey) || '').trim();
  if (!nodeId || !fieldKey) return { ok: false, error: 'no_target_field' };

  var body = {
    nodeId: nodeId,
    fieldKey: fieldKey,
    action: (payload && payload.action) || '',
    environment: environment
  };
  if (payload && payload.workflowId) body.workflowId = payload.workflowId;
  if (payload && payload.label) body.label = payload.label;

  var res = await apiFetch(
    ctx.base + '/inspector/targeting/begin',
    { method: 'POST', body: JSON.stringify(body) },
    ctx.apiKey
  );
  var data = (res && res.data) || {};
  if (!res.ok) {
    // `local_disabled` / `local_unavailable` are passed through with the
    // server's own sentence: the operator's switch is the fix, and a generic
    // failure would hide it.
    return {
      ok: false,
      reason: data.reason || res.error,
      error: data.error || res.message || 'The browser environment could not be selected.',
      environment: environment
    };
  }

  var target = data.target || null;

  // NOTHING IS STORED HERE, in either environment, and that is the whole point.
  //
  // A previous revision adopted the returned target immediately for `local`. It
  // cannot: LOCAL is the server's shared browser, and the server answers a LOCAL
  // begin by raising an in-page approval prompt. Storing the destination before
  // that prompt is answered would make the Allow button decorative — the field
  // would already be bound, and a pick could land in a node the operator never
  // confirmed. Approval is what writes it (see AB_CONSENT_DECIDE).
  //
  // REMOTE stores nothing either, for the mirror-image reason: the destination
  // arrives when the Authorization Code is redeemed, not when it is issued.
  //
  // So in both environments the destination is written by the ACT that settles
  // it, never by this call.
  return {
    ok: true,
    environment: environment,
    step: data.step || 'targeting',
    target: target,
    paired: !!data.paired,
    runtime: data.runtime || '',
    // TRUE for LOCAL — the browser this server can actually launch. Named for
    // what it opens; `openRemoteBrowser` said the opposite of what it did.
    openServerBrowser: !!data.openServerBrowser,
    consent: data.consent || null,
    // REMOTE only: the code + Base URL the operator carries to their own
    // browser. Null for LOCAL, where there is nothing to transcribe.
    authorization: data.authorization || null
  };
}

/**
 * Redeem an Authorization Code. THE REMOTE PATH, and the only writer of a
 * REMOTE destination.
 *
 * This is what the operator's own browser does with the code the dashboard
 * showed them. It is the mirror of consentDecide(): both end with a target field
 * in storage, but they answer different questions —
 *
 *   consentDecide  "the server asked me to confirm a field; I approve."  LOCAL
 *   inspectorPair  "I hold a code the server minted; here it is."        REMOTE
 *
 * `baseUrl` is accepted as an argument because in REMOTE the extension may not
 * know the server's address yet — that is exactly the gap the Base URL box
 * fills. It is persisted on success so subsequent calls need no argument.
 */
async function inspectorPair(payload) {
  var typedBase = normalizeBase((payload && payload.baseUrl) || '');
  var code = String((payload && payload.code) || '').trim();
  if (!code) return { ok: false, error: 'Enter the authorization code from the dashboard.' };

  var ctx = await inspectorContext();
  // A typed address wins over a resolved one: the operator is telling us where
  // the server is because nothing else could.
  var base = typedBase || (ctx.error ? '' : ctx.base);
  if (!base) return { ok: false, error: 'Enter the Base URL of your server.' };

  var res = await apiFetch(
    base + '/inspector/pair',
    { method: 'POST', body: JSON.stringify({ code: code }) },
    ctx.apiKey
  );
  var data = (res && res.data) || {};
  if (!res.ok) {
    return {
      ok: false,
      reason: data.reason || res.error,
      error: data.error || res.message || 'That authorization code was not accepted.'
    };
  }

  // Persist the address that worked, so the next field needs only a code.
  if (typedBase) await new Promise(function (r) {
    chrome.storage.local.set({ ab_baseUrl: typedBase }, function () { r(); });
  });

  if (data.targetFieldId) {
    await setTargetFieldId(data.targetFieldId);
    await setTargetEnvironment('remote');
  }

  return { ok: true, paired: true, environment: 'remote', targetFieldId: data.targetFieldId || '' };
}

/** Read the current browser mode (Remote / Local) for the popup's indicator. */
async function getBrowserMode() {
  var ctx = await inspectorContext();
  if (ctx.error) return { ok: false, error: ctx.error };
  return apiFetch(ctx.base + '/browser-mode', { method: 'GET' }, ctx.apiKey);
}

/** Switch mode from the extension. 409 means the backend refused, with a note. */
async function setBrowserMode(payload) {
  var ctx = await inspectorContext();
  if (ctx.error) return { ok: false, error: ctx.error };
  var mode = payload && payload.mode;
  if (!mode) return { ok: false, error: 'no_mode' };

  var res = await apiFetch(
    ctx.base + '/browser-mode',
    { method: 'POST', body: JSON.stringify({ mode: mode }) },
    ctx.apiKey
  );
  var data = res.data || {};
  if (!res.ok) {
    return { ok: false, reason: data.note || res.error, error: data.error || 'Could not switch mode.', data: data };
  }
  return { ok: true, data: data };
}

// ════════════════════════════════════════════════════════════════
// Remote -> Local handoff
//
// Thin wrappers over lib/ab-handoff.js. The base URL is resolved from settings
// here rather than passed in from the popup, so the extension can only ever pair
// with the backend it is configured for -- a code typed into the wrong window
// cannot redirect it somewhere else.
//
// NOTE these deliberately do NOT require an API key, unlike every other call in
// this worker. The whole point of the pairing code is that the extension joins a
// session WITHOUT holding the key that controls the entire instance, so demanding
// one here would defeat the security model and also break the realistic case:
// a user installing the extension for the first time has a code but no key.
// ════════════════════════════════════════════════════════════════

function handoffAvailable() {
  return (typeof ABHandoff !== 'undefined') && ABHandoff;
}

// Resolved through the same internal path as everything else, so this cannot
// ask for a Base URL the popup no longer collects.
async function handoffBase() {
  var ctx = await inspectorContext();
  return (ctx && ctx.base) || '';
}

async function handoffPair(payload) {
  if (!handoffAvailable()) return { ok: false, error: 'Handoff module failed to load.' };
  var base = await handoffBase();
  if (!base) {
    // Was 'Set the backend Base URL in this popup first, then enter the code.'
    // There is no such box any more, and the address is the server's to state.
    return {
      ok: false,
      reason: 'runtime_context_unavailable',
      error: 'This browser has not been given a backend address by the server yet.'
    };
  }
  var res = await ABHandoff.pairWithCode(base, payload && payload.code);
  return res;
}

async function handoffApply() {
  if (!handoffAvailable()) return { ok: false, error: 'Handoff module failed to load.' };
  var base = await handoffBase();
  return ABHandoff.applyHandoff({ baseUrl: base });
}

async function handoffStatus() {
  if (!handoffAvailable()) return { ok: false, paired: false, error: 'Handoff module failed to load.' };
  var s = await ABHandoff.status();
  return Object.assign({ ok: true }, s);
}

async function handoffUnpair() {
  if (!handoffAvailable()) return { ok: false, error: 'Handoff module failed to load.' };
  await ABHandoff.clearPairing();
  return { ok: true };
}

/**
 * Toggle the picker in the active tab.
 *
 * The content script is asked first; if it is not there (a tab opened before
 * the extension was installed, or reloaded) it is injected on the spot, so the
 * user is never told to reload the page.
 */
async function toggleInspector(desired) {
  return new Promise(function (resolve) {
    chrome.tabs.query({ active: true, currentWindow: true }, function (tabs) {
      var tab = tabs && tabs[0];
      if (!tab || tab.id == null) { resolve({ ok: false, error: 'no_active_tab' }); return; }

      var type = desired === 'stop' ? 'ab-inspector-stop' : 'ab-inspector-start';
      chrome.tabs.sendMessage(tab.id, { type: type }, function (resp) {
        if (!chrome.runtime.lastError) { resolve(resp || { ok: true }); return; }
        if (!chrome.scripting || !chrome.scripting.executeScript) {
          resolve({ ok: false, error: 'no_content_script' });
          return;
        }
        // Same file order as the manifest: extraction core and selectors must
        // exist before inspector.js runs.
        chrome.scripting.executeScript({
          target: { tabId: tab.id },
          files: ['lib/ab-inspect.js', 'content/selector.js', 'content/inspector.js']
        }, function () {
          if (chrome.runtime.lastError) {
            resolve({ ok: false, error: 'inject_failed', message: chrome.runtime.lastError.message });
            return;
          }
          chrome.tabs.sendMessage(tab.id, { type: type }, function (resp2) {
            if (chrome.runtime.lastError) { resolve({ ok: false, error: 'no_content_script' }); return; }
            resolve(resp2 || { ok: true });
          });
        });
      });
    });
  });
}

// The keyboard shortcut works with no popup open. Note that Chrome may decline
// to register Ctrl+Shift+C because DevTools claims it; inspector.js also listens
// for the chord in-page, so the gesture works either way.
if (chrome.commands && chrome.commands.onCommand) {
  chrome.commands.onCommand.addListener(function (command) {
    if (command === 'toggle-inspector') toggleInspector('toggle');
  });
}

// Relay a control message to the active tab's content script.
async function relayToActiveTab(message) {
  return new Promise(function (resolve) {
    chrome.tabs.query({ active: true, currentWindow: true }, function (tabs) {
      var tab = tabs && tabs[0];
      if (!tab || tab.id == null) { resolve({ ok: false, error: 'no_active_tab' }); return; }
      chrome.tabs.sendMessage(tab.id, message, function (resp) {
        if (chrome.runtime.lastError) {
          resolve({ ok: false, error: 'no_content_script' });
        } else {
          resolve(resp || { ok: true });
        }
      });
    });
  });
}

chrome.runtime.onMessage.addListener(function (msg, _sender, sendResponse) {
  if (!msg || !msg.type) return;
  switch (msg.type) {
    case 'AB_SEND_FLOW':
      sendFlow(msg.payload).then(sendResponse);
      return true; // async
    case 'AB_CHECK':
      checkConnection().then(sendResponse);
      return true; // async
    case 'AB_LIST_WORKFLOWS':
      listWorkflows().then(sendResponse);
      return true; // async
    case 'AB_RUN_SAVED':
      runSavedWorkflow(msg.payload).then(sendResponse);
      return true; // async
    case 'AB_LIVE_START':
      startLive(msg.payload).then(sendResponse);
      return true; // async
    case 'AB_LIVE_STOP':
      sendResponse(stopLive(msg.payload));
      return false;
    case 'AB_OPEN_PANEL':
      openPanel().then(sendResponse);
      return true; // async
    case 'AB_RELAY':
      relayToActiveTab(msg.message).then(sendResponse);
      return true; // async

    // ---- Element Inspector -------------------------------------------------
    // Sent by content/inspector.js when the user presses "Confirm & Add to Node".
    case 'ab-inspector-submit':
      submitElement(msg).then(sendResponse);
      return true; // async
    case 'AB_INSPECTOR_SESSION':
      inspectorSession().then(sendResponse);
      return true; // async
    // There is deliberately NO 'AB_INSPECTOR_PAIR' case here any more.
    //
    // It used to route to inspectorPair(), which redeemed a user-typed
    // Authorization Code against POST /inspector/pair. Both the function and
    // the code architecture are gone: the server now binds the target field
    // itself when the operator clicks the crosshair (LOCAL, silently) or
    // approves the request (REMOTE, via AB_CONSENT_DECIDE below). No caller
    // in this repo sends this message.
    //
    // Note AB_HANDOFF_PAIR further down is a DIFFERENT subsystem — it binds a
    // BROWSER SESSION, not a target field — and is intentionally untouched.
    // ---- Browser Environment: the LOCAL / REMOTE choice ------------------
    // The FIRST step of targeting, offered here as well as in the dashboard,
    // because this popup is the surface reached from inside the browser being
    // targeted. Both cases delegate to the routes the dashboard chooser already
    // uses; neither adds a binding rule of its own.
    case 'AB_TARGETING_OPTIONS':
      targetingOptions(msg.payload).then(sendResponse);
      return true; // async
    case 'AB_TARGETING_BEGIN':
      targetingBegin(msg.payload).then(sendResponse);
      return true; // async
    case 'AB_INSPECTOR_PAIR':
      inspectorPair(msg.payload).then(sendResponse);
      return true; // async
    case 'AB_INSPECTOR_UNPAIR':
      inspectorUnpair().then(sendResponse);
      return true; // async
    case 'AB_INSPECTOR_TOGGLE':
      toggleInspector(msg.desired).then(sendResponse);
      return true; // async

    // ---- Remote targeting consent -----------------------------------------
    // How a REMOTE browser acquires its target: by answering a question the
    // server delivered, never by transcribing a code. (A LOCAL browser needs
    // nothing at all — the server binds the field when the crosshair is used.)
    // Which browser am I? Asked by content/consent.js before it starts polling,
    // so a local browser never runs the approval loop at all, and by the popup
    // so it can state the environment instead of leaving the operator guessing.
    case 'AB_ENVIRONMENT':
      browserEnvironment().then(function (env) {
        sendResponse({ ok: true, environment: env });
      });
      return true; // async
    case 'AB_CONSENT_LIST':
      consentList().then(sendResponse);
      return true; // async
    case 'AB_CONSENT_DECIDE':
      consentDecide(msg.payload).then(sendResponse);
      return true; // async
    case 'AB_MODE_GET':
      getBrowserMode().then(sendResponse);
      return true; // async
    case 'AB_MODE_SET':
      setBrowserMode(msg.payload).then(sendResponse);
      return true; // async

    // ---- Remote <-> Local handoff -----------------------------------------
    case 'AB_HANDOFF_PAIR':
      handoffPair(msg.payload).then(sendResponse);
      return true; // async
    case 'AB_HANDOFF_APPLY':
      handoffApply().then(sendResponse);
      return true; // async
    case 'AB_HANDOFF_STATUS':
      handoffStatus().then(sendResponse);
      return true; // async
    case 'AB_HANDOFF_UNPAIR':
      handoffUnpair().then(sendResponse);
      return true; // async
    default:
      return false;
  }
});
